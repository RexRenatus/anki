"""Write the frozen Unicode 10.0.0 tables of rslib/src/unicode10.rs.

Usage: python3 tools/unicode10/generate.py GENERAL_CATEGORY_RSV

GENERAL_CATEGORY_RSV is tables/general_category.rsv from the published
unic-ucd-category 0.9.0 crate. It lists Unicode 10.0.0's general categories as
sorted, inclusive char ranges, and leaves out the unassigned (Cn) gaps. Every
listed range is assigned; the marks are the Mn, Mc and Me ranges. Adjacent
ranges are merged, and the ASSIGNED and MARK constants of
rslib/src/unicode10.rs are rewritten in place. The script prints the number of
table rows, merged ranges and scalar values it wrote.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parents[2] / "rslib" / "src" / "unicode10.rs"
HEADER = "// WARNING: Auto-generated by the `unic-gen` crate."
OPEN = "CharDataTable::Range(&["
CLOSE = "])"
ROW = re.compile(
    r"^    \(chars!\('\\u\{([0-9a-f]+)\}'\.\.='\\u\{([0-9a-f]+)\}'\), ([A-Z][a-z])\),$"
)
# Every general category but Cn (the gaps) and Cs (surrogates are not chars).
CATEGORIES = set(
    "Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So "
    "Zs Zl Zp Cc Cf Co".split()
)
MARKS = {"Mn", "Mc", "Me"}
SURROGATES = (0xD800, 0xDFFF)


def read_rows(path: Path) -> list[tuple[int, int, str]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != HEADER:
        sys.exit(f"{path}: not unic-gen's table (first line differs)")
    body = [line for line in lines if not line.startswith("//")]
    if len(body) < 3 or body[0] != OPEN or body[-1] != CLOSE:
        sys.exit(f"{path}: the range table's open or close line differs")
    rows = []
    last = -1
    for line in body[1:-1]:
        match = ROW.match(line)
        if not match:
            sys.exit(f"{path}: unexpected line {line!r}")
        lo, hi, category = int(match[1], 16), int(match[2], 16), match[3]
        if category not in CATEGORIES:
            sys.exit(f"{path}: unexpected category {category}")
        if not last < lo <= hi <= 0x10FFFF:
            sys.exit(f"{path}: range {lo:X}..{hi:X} is not sorted and disjoint")
        rows.append((lo, hi, category))
        last = hi
    return rows


def merge(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    merged: list[tuple[int, int]] = []
    for lo, hi in ranges:
        if merged and merged[-1][1] + 1 == lo:
            merged[-1] = (merged[-1][0], hi)
        else:
            merged.append((lo, hi))
    return merged


def scalar_values(ranges: list[tuple[int, int]]) -> int:
    total = 0
    for lo, hi in ranges:
        total += hi - lo + 1
        overlap = min(hi, SURROGATES[1]) - max(lo, SURROGATES[0]) + 1
        total -= max(overlap, 0)
    return total


def replace_table(text: str, name: str, ranges: list[tuple[int, int]]) -> str:
    pattern = re.compile(
        r"(const " + name + r": &\[\(u32, u32\)\] = &\[)(.*?)(\];)", re.DOTALL
    )
    if len(pattern.findall(text)) != 1:
        sys.exit(f"{TARGET}: expected one {name} constant")
    rows = "".join(f"    (0x{lo:04X}, 0x{hi:04X}),\n" for lo, hi in ranges)
    return pattern.sub(lambda m: m[1] + "\n" + rows + m[3], text)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    rows = read_rows(Path(argv[1]))
    assigned = merge([(lo, hi) for lo, hi, _ in rows])
    mark = merge([(lo, hi) for lo, hi, category in rows if category in MARKS])
    text = TARGET.read_text(encoding="utf-8")
    text = replace_table(text, "ASSIGNED", assigned)
    text = replace_table(text, "MARK", mark)
    TARGET.write_text(text, encoding="utf-8")
    print(
        f"rows={len(rows)} assigned_ranges={len(assigned)} "
        f"mark_ranges={len(mark)} assigned={scalar_values(assigned)} "
        f"mark={scalar_values(mark)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
